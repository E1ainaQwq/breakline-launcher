const assert = require('node:assert/strict')
const crypto = require('node:crypto')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const helper = fs.readFileSync(path.join(root, 'build/memory-cleanup/MemoryCleanup.cs'), 'utf8')
const service = fs.readFileSync(path.join(root, 'src/main/services/MemoryCleanup.ts'), 'utf8')
const main = fs.readFileSync(path.join(root, 'src/main/index.ts'), 'utf8')
const ui = fs.readFileSync(path.join(root, 'src/renderer/App.tsx'), 'utf8')
const helperBinary = fs.readFileSync(path.join(root, 'resources/memory-cleanup-helper.exe'))

assert.match(helper, /SystemMemoryListInformation\s*=\s*0x50/)
assert.match(helper, /MemoryEmptyWorkingSets\s*=\s*2/)
assert.match(helper, /MemoryFlushModifiedList\s*=\s*3/)
assert.doesNotMatch(helper, /PurgeStandby|MemoryPurgeStandby|\b4\s*;/i)
assert.match(helper, /args\.Length\s*!=\s*0/)
assert.equal((helper.match(/Apply\(Memory(?:EmptyWorkingSets|FlushModifiedList)\)/g) || []).length, 2)
assert.match(fs.readFileSync(path.join(root, 'build/memory-cleanup/MemoryCleanup.manifest'), 'utf8'), /level="requireAdministrator"/)
assert.match(service, /Start-Process -FilePath \$p -Verb RunAs -Wait -PassThru/)
const expectedHelperHash = '7ADFA369C5101378D4BAA82566D5EEE6D62E14C00B8DB32B32066EBE90202277'
assert.match(service, new RegExp(expectedHelperHash))
assert.equal(crypto.createHash('sha256').update(helperBinary).digest('hex').toUpperCase(), expectedHelperHash)
assert.match(service, /完整性校验失败，已拒绝提权/)
assert.match(main, /getRuntimeSettings\(\)\.memoryCleanupEnabled === true/)
assert.match(ui, /HDD（机械硬盘）开启会产生负优化；开启后启动速度会变慢/)
assert.match(ui, /内存优化模式/)

console.log('PASS fixed 0x50/2+3 helper, no arbitrary args or standby purge, elevated manifest, opt-in launch path, and HDD notice')
